public class Main {
    public static void main(String[] args) {
        for (int numero = 1; numero <= 5; numero++) {
            System.out.println("Numero: " + numero);
        }

        int intento = 1;

        while (intento <= 3) {
            System.out.println("Practica numero " + intento);
            intento++;
        }
    }
}
